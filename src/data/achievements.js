// Собирает полный список достижений (~1000, из них "Редкие" зависят от
// реального числа тем в таблице words) с посчитанным unlocked по stats.
// topics — необязательный параметр (результат getPath().topics); без него
// категория "Редкие" останется без пер-темных достижений, но не сломается.
export function buildAchievements(stats, topics) {
  const all = [
    ...tasksAchievements(),
    ...streakAchievements(),
    ...wordsAchievements(),
    ...hourAchievements(),
    ...weekdayAchievements(),
    ...mistakeStreakAchievements(),
    ...mistakeTotalAchievements(),
    ...memeAchievements(),
    ...rareAchievements(topics),
  ];
  return all.map((a) => ({ ...a, unlocked: Boolean(a.check(stats)) }));
}
