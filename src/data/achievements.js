const ROMAN = [
  "", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X",
  "XI", "XII", "XIII", "XIV", "XV", "XVI", "XVII", "XVIII", "XIX", "XX",
];
function toRoman(n) {
  return n < ROMAN.length ? ROMAN[n] : String(n);
}

// Русское склонение существительного после числительного: 1 задание, 2 задания,
// 5 заданий, 21 задание, 25 заданий и т.п.
function pluralRu(n, one, few, many) {
  const mod10 = Math.abs(n) % 10;
  const mod100 = Math.abs(n) % 100;
  if (mod100 > 10 && mod100 < 20) return many;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}

// Округление порога до "красивого" числа — чтобы кривая роста не выдавала
// пороги вида 1247, 1863 и т.п.
function niceRound(n) {
  if (n < 20) return Math.round(n);
  if (n < 100) return Math.round(n / 5) * 5;
  if (n < 500) return Math.round(n / 10) * 10;
  if (n < 2000) return Math.round(n / 25) * 25;
  if (n < 5000) return Math.round(n / 50) * 50;
  if (n < 20000) return Math.round(n / 100) * 100;
  return Math.round(n / 500) * 500;
}

// Строго возрастающая серия из `count` порогов от `start` до `end` по
// выпуклой кривой (t^1.6) — часто в начале (быстрые ранние награды), редко
// к концу (дальние амбициозные цели). Дубликаты после округления схлопываем
// принудительным +1.
function buildMilestones(count, start, end) {
  const result = [];
  let prev = 0;
  for (let i = 0; i < count; i++) {
    const t = count === 1 ? 1 : i / (count - 1);
    const raw = start + (end - start) * Math.pow(t, 1.6);
    let v = niceRound(raw);
    if (v <= prev) v = prev + 1;
    result.push(v);
    prev = v;
  }
  return result;
}

// Строит серию пороговых достижений по одной метрике из stats, с названиями
// из тематического пула (пул крутится по кругу; при повторном проходе — к
// названию добавляется римский номер тира: "Марафонец", "Марафонец II", ...).
function buildMilestoneSeries({ prefix, cat, icon, metricKey, count, start, end, namePool, descFn }) {
  const thresholds = buildMilestones(count, start, end);
  return thresholds.map((threshold, i) => {
    const tier = Math.floor(i / namePool.length) + 1;
    const base = namePool[i % namePool.length];
    const title = tier === 1 ? base : `${base} ${toRoman(tier)}`;
    return {
      id: `${prefix}_${i}`,
      cat,
      icon,
      title,
      desc: descFn(threshold),
      check: (stats) => (Number(stats?.[metricKey]) || 0) >= threshold,
    };
  });
}

