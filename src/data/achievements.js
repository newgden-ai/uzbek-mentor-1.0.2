// 1 — полная система достижений (~1000 шт. на 5 категорий).
//
// Раньше был статичный массив из 17 "достижений-превью" с ВРУЧНУЮ прописанным
// unlocked: true/false — то есть витрина, никак не связанная с реальным
// прогрессом пользователя. Переписывать это в 1000 таких же строк было бы
// ещё хуже: фейковый список, который никогда не обновляется.
//
// Вместо этого: для категорий с понятной числовой метрикой (задания/серии/
// слова) пороги генерируются кривой роста (buildMilestones) и берут имя из
// тематического пула (крутится по кругу, с римским номером тира при
// повторном проходе пула — так на 200 достижений не нужно 200 уникальных
// вручную придуманных названий, но общая тема выдержана).
// Категории "юмор"/"редкие" собраны из реально проверяемых условий: часы/дни
// активности, серии ошибок, "мемные" числа заданий, реальные темы из "Пути"
// (динамически, по факту содержимого таблицы words) и т.п.
//
// unlocked считается один раз, здесь же, функцией buildAchievements(stats),
// от статистики, которую отдаёт бэкенд (Code.gs: getStats) — не хранится.
//
// ВАЖНО: категория "редкие" зависит от реального количества тем в таблице
// words (см. per-topic блок) — поэтому итоговое число достижений в ней (и
// общий итог по всем категориям) будет не РОВНО 1000, а околостоящим —
// это осознанный компромисс в пользу того, чтобы достижения были настоящими,
// а не фейковой витриной.

