// По одному достижению за каждую реально пройденную тему (topics приходит с
// бэкенда через getPath — те же данные, что видны на экране "Путь"). Список
// динамический: сколько тем в таблице words — столько и достижений здесь.
function topicAchievements(topics) {
  if (!Array.isArray(topics)) return [];
  return topics
    .filter((t) => t.total > 0)
    .map((t, i) => ({
      id: `rare_topic_${i}_${t.name}`,
      cat: "rare",
      icon: Gem,
      title: `Тема закрыта: ${t.name}`,
      desc: `Все слова темы «${t.name}» (${t.total}) освоены`,
      check: () => t.mastered >= t.total,
    }));
}

function rareAchievements(topics) {
  const oneOffs = oneOffRareAchievements().map((a) => ({ ...a, cat: "rare", icon: Gem }));
  return [...levelAchievements(), ...oneOffs, ...topicAchievements(topics)];
}

